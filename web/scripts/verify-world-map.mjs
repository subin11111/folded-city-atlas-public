import fs from 'node:fs/promises';
import {createRequire} from 'node:module';
import {fileURLToPath} from 'node:url';
import assert from 'node:assert/strict';
const require=createRequire(import.meta.url),{chromium}=require(require.resolve('playwright',{paths:[process.env.PLAYWRIGHT_NODE_MODULES]}));
const base=process.env.WORLD_TEST_URL||'http://127.0.0.1:8776';
const out=new URL('../../docs/assets/world-map-20261020/',import.meta.url);await fs.mkdir(out,{recursive:true});
const browser=await chromium.launch({headless:true,channel:'msedge'}),errors=[],failed=[],remote=[];
const page=await browser.newPage({viewport:{width:1440,height:1000}});
page.on('pageerror',e=>errors.push(e.message));
page.on('console',m=>{if(m.type()==='error')errors.push(m.text());});
page.on('requestfailed',r=>{if(!r.failure()?.errorText.includes('ABORTED'))failed.push({url:r.url(),error:r.failure()?.errorText});});
page.on('response',r=>{if(r.url().includes('openfreemap.org'))remote.push({url:r.url(),status:r.status()});});
try{
 await page.goto(base);await page.waitForFunction(()=>window.foldedCity?.state.three?.stats().worldMap?.ready,{timeout:25000});
 await page.locator('#loadingScreen').waitFor({state:'hidden'});
 await page.waitForFunction(()=>window.foldedCity.state.three.stats().worldMap.campusDraws>2,{timeout:10000});
 await page.waitForTimeout(1500);
 const campus=await page.evaluate(()=>window.foldedCity.state.three.stats());
 await page.screenshot({path:fileURLToPath(new URL('campus.png',out))});
 assert.deepEqual(errors,[],'교내 지도 초기 렌더링 오류');
 assert.equal(campus.buildings,48);assert.equal(campus.worldMap.maxBounds,null);
 await page.evaluate(()=>window.foldedCity.state.three.worldView({center:[126.9779,37.5665],zoom:12,pitch:0,bearing:0}));
 await page.waitForTimeout(1500);await page.screenshot({path:fileURLToPath(new URL('seoul.png',out))});
 const seoul=await page.evaluate(()=>({stats:window.foldedCity.state.three.stats().worldMap,title:document.querySelector('#mapTitle').textContent}));
 assert.equal(seoul.title,'주변 지도');assert.ok(Math.abs(seoul.stats.center[0]-126.9779)<.00001);
 await page.evaluate(()=>window.foldedCity.state.three.worldView({center:[10,25],zoom:1.5,pitch:0,bearing:0}));
 await page.waitForTimeout(1500);await page.screenshot({path:fileURLToPath(new URL('world.png',out))});
 const world=await page.evaluate(()=>window.foldedCity.state.three.stats().worldMap);assert.equal(world.zoom,1.5);
 assert.equal(await page.locator('#mapTitle').textContent(),'세계 지도');
 await page.locator('#campusHome').click();await page.waitForTimeout(1500);
 assert.equal(await page.locator('#mapTitle').textContent(),'건국대학교 서울캠퍼스');
 await page.locator('.scene-label.available').click();
 await page.waitForFunction(()=>document.querySelector('#photoStage')?.dataset.photoId&&document.querySelector('#photoStage')?.dataset.loading==='false');
 await page.screenshot({path:fileURLToPath(new URL('entrance.png',out))});
 const entrance=await page.locator('#photoStage').getAttribute('data-photo-id');
 await page.locator('#walkExit').click();await page.locator('#campusHome').click();
 await page.setViewportSize({width:390,height:844});await page.waitForTimeout(1500);
 await page.screenshot({path:fileURLToPath(new URL('mobile.png',out)),fullPage:true});
 assert.equal(await page.evaluate(()=>document.documentElement.scrollWidth>innerWidth),false);
 await page.locator('#sheetGrip').press('Home');await page.waitForTimeout(450);
 await page.screenshot({path:fileURLToPath(new URL('mobile-collapsed.png',out)),fullPage:true});
 await page.evaluate(()=>window.foldedCity.location.startRecorded('outside'));await page.waitForTimeout(1300);
 const replay=await page.evaluate(()=>({index:window.foldedCity.location.state.replayIndex,stats:window.foldedCity.state.three.stats()}));
 assert.ok(replay.index>0);assert.ok(replay.stats.locationTracks.some(t=>t.kind==='raw-recording'));
 await page.screenshot({path:fileURLToPath(new URL('measured-gnss.png',out)),fullPage:true});
 await page.evaluate(()=>window.foldedCity.location.stop());
 assert.deepEqual(errors,[]);assert.equal(failed.length,0);assert.ok(remote.some(r=>r.status===200&&r.url.includes('/planet')));
 const result={passed:true,campus,seoul,world,entrance,measuredReplay:{index:replay.index,tracks:replay.stats.locationTracks},remoteRequestCount:remote.length,remoteErrors:remote.filter(r=>r.status>=400),errors,failed};
 await fs.writeFile(new URL('verification.json',out),JSON.stringify(result,null,2)+'\n');console.log(JSON.stringify(result,null,2));
}catch(error){await page.screenshot({path:fileURLToPath(new URL('failure.png',out))});console.log(JSON.stringify({errors,failed,remoteErrors:remote.filter(r=>r.status>=400)},null,2));throw error;}
finally{await browser.close();}
